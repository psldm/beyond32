"""The dodecagonal point group D6d = -12m2 of the Ta1.6Te quasicrystal: pairing functions on
the in-plane circle (Appendix B and Table 10 of the paper).

The point group of the dodecagonal quasicrystal Ta1.6Te is D6d (Hermann-Mauguin -12m2;
Yamamoto, Acta Cryst. A 60, 142 (2004)), of order 24.  It contains no inversion, no
horizontal mirror and no true twelve-fold rotation: its principal operation is the
twelve-fold rotoreflection S12 = sigma_h C12.  In Yamamoto's orientation the group is
generated by

    S12 = diag(1, 1, -1) . R_z(30 deg)      (the rotoreflection about z),
    C2' = the two-fold rotation about the in-plane axis at 15 deg,

so that the six vertical mirror planes sigma_d contain the in-plane directions 30 deg . j
(the framework edges) and the six two-fold axes C2' lie at 15 deg + 30 deg . j.  The 24
elements are the closure of the two generators as exact 3x3 matrices over Q(sqrt 3)
(``elements``, ``matrix``); every element is diag(O, eps) with O in O(2) and eps = +-1:

* ``S_k`` = S12^k (k = 0..11): in-plane rotation by 30 k deg, eps = (-1)^k
  (k even: the rotations E, C6, C3, C2, ...; k odd: the rotoreflections S12, S4, S12^5, ...),
* ``P_k`` (k = 0..11): in-plane reflection across the line at 15 k deg, eps = (-1)^k
  (k even: the mirror sigma_d containing the direction 15 k deg; k odd: the two-fold
  rotation C2' about the axis at 15 k deg).

Nine conjugacy classes, E, 2 S12, 2 C6, 2 S4, 2 C3, 2 S12^5, C2, 6 C2', 6 sigma_d, and nine
irreps A1, A2, B1, B2, E1, ..., E5 (sum of d^2 = 24).  The one-dimensional characters are
read off the matrices, B1(g) = det g, B2(g) = g_zz, A2 = B1 B2 -- so B1 is +1 on the
two-fold axes and -1 on the mirrors, B2 the reverse, A2 is -1 on both -- and E_m is the
trace of the action on span{cos m phi, sin m phi} (``character_table_D6d``).  Abstractly
D6d is isomorphic to the dihedral group of order 24, but as a point group it is not D12:
half of its operations are improper.

Pair functions on the in-plane circle k = (cos phi, sin phi, 0)
--------------------------------------------------------------
The singlet gap psi(phi) transforms as a scalar, psi -> psi(g^-1 k), and the triplet
d-vector as an axial vector, d -> det(g) g d(g^-1 k).  For each harmonic order m the module
builds the exact representation matrices on the sectors

* ``singlet``:          span{cos m phi, sin m phi}                 (even m in the paper),
* ``triplet_inplane``:  span{cos m phi, sin m phi} x {e_x, e_y}    (odd m),
* ``triplet_z``:        span{cos m phi, sin m phi} e_z             (odd m),

decomposes them with the character table and computes the basis functions of every irrep
from the exact isotypic projectors (the reduced row echelon form of their image, so that
the basis functions are canonical): Table 10 (``sector_decomposition``, ``sector_basis``,
``table10``).  Pinned in the tests:

* singlet: m = 0 -> A1, +-2 -> E2, +-4 -> E4, +-6 -> B1 + B2 (sin 6 phi in B1, cos 6 phi in B2);
* triplet, in-plane: m = +-1 -> B1 + B2 + E4, +-3 -> E2 + E4, +-5 -> A1 + A2 + E2;
  d_z: m = +-1 -> E1, +-3 -> E3, +-5 -> E5;
* the antisymmetric spin-orbit vector g(k) (odd in k, axial) has A1 content only in the
  in-plane m = +-5 sector -- within the range |m| <= 6 of Table 10; the sectors depend on
  m mod 12 only, so m = 7 = -5 (mod 12) is the same E5 sector -- with
  g ~ (sin 5 phi, cos 5 phi, 0), and no g_z component for any odd m
  (``asoc_A1_content``, ``asoc_vector``);
* the restriction to the approximant point group D2d = -42m generated by S4 = S12^3 and the
  two-fold axis at 15 deg: A1 -> A1, A2 -> A2, B1 -> B1, B2 -> B2, E1, E3, E5 -> E,
  E2 -> B1 + B2, E4 -> A1 + A2 (``restriction_to_D2d``);
* the orbit of an in-plane axial vector (a magnetic field) under D6d, with H -> -H
  included, consists of all multiples of 30 deg, so in-plane field-angle dependences have
  period 30 deg (``field_orbit``, ``field_angle_period``).

Everything here is exact: the matrices, characters and projectors live in Q(sqrt 3) (the
rotoreflection S12 brings in cos 30 deg = sqrt3/2), canonicalised with ``sympy.expand`` as
in the rest of the package; the results are integer multiplicities and closed
trigonometric forms.
"""
from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from typing import Dict, List, Sequence, Tuple

import sympy as sp
from sympy import ImmutableMatrix, Matrix, S, pi, sqrt

